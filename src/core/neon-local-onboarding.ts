import { readFile, stat } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { neonInput, type NeonInput } from '../shared/neon-models.ts';

/** Only the Host owner can select a local fixture configuration. Cloud-only
 * configurations are rejected here so this path cannot create billable resources.
 */
export async function readLocalNeonConfig(configPath: string): Promise<NeonInput> {
  if (!isAbsolute(configPath)) throw new Error('Local Neon configuration must use an absolute file path.');
  const info = await stat(configPath).catch(() => { throw new Error('Local Neon configuration cannot be read.'); });
  if (!info.isFile() || info.size > 32768) throw new Error('Local Neon configuration must be a JSON file smaller than 32 KiB.');
  let value: unknown;
  try { value = JSON.parse(await readFile(configPath, 'utf8')); }
  catch { throw new Error('Local Neon configuration is not valid JSON.'); }
  const parsed = neonInput.safeParse(value);
  if (!parsed.success || !parsed.data.localEndpoint) {
    throw new Error('Choose provider.json generated by stellane-neon start. A loopback localEndpoint is required; cloud configurations are not accepted.');
  }
  return parsed.data;
}
